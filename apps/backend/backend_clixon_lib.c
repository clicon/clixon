/*! Set debug level.
 *
 * @param[in]  h       Clixon handle
 * @param[in]  xe      Request: <rpc><xn></rpc>
 * @param[out] cbret   Return xml tree, eg <rpc-reply>..., <rpc-error..
 * @param[in]  arg     client-entry
 * @param[in]  regarg  User argument given at rpc_callback_register()
 * @retval     0       OK
 * @retval    -1       Error
 */
static int
from_client_debug(clixon_handle h,
                  cxobj        *xe,
                  cbuf         *cbret,
                  void         *arg,
                  void         *regarg)
{
    int      retval = -1;
    uint32_t level;
    char    *valstr;

    if ((valstr = xml_find_body(xe, "level")) == NULL){
        if (netconf_missing_element(cbret, "application", "level", NULL) < 0)
            goto done;
        goto ok;
    }
    level = atoi(valstr);

    clixon_debug_init(h, level); /* 0: dont debug, 1:debug */
    setlogmask(LOG_UPTO(level?LOG_DEBUG:LOG_INFO)); /* for syslog */
    clixon_log(h, LOG_NOTICE, "%s debug: 0x%x", __func__, clixon_debug_get());
    cprintf(cbret, "<rpc-reply xmlns=\"%s\"><ok/></rpc-reply>", NETCONF_BASE_NAMESPACE);
 ok:
    retval = 0;
 done:
    return retval;
}

